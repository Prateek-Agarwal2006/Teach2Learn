"""Place the two systems' language results side by side, from raw results files.

    python3 scripts/compare_systems.py --finetuned sweepB-*.json fix-*.json \
        --rag "../LbT (RAG Based)…/sweepB-rag.json" > ../PHASE1_COMPARISON.md

Only the three shared components make a cross-system number mean anything: the same
lesson bank, the byte-identical translation.py, and one judge with one prompt. So this
compares only what those produce -- fidelity, fluency, and the mechanical boundary checks.
Neither system's native grading appears here: the portal's adapter grades itself inline
and the RAG tool has a separate scorer chain, and RAG_TEST_PLAN.md explains at length why
placing those beside each other would be meaningless.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from report_sweep import SUBJECT_NAMES  # noqa: E402

LANGUAGE_NAMES: dict[str, str] = {}


def load(paths: list[str]) -> list[dict]:
    runs = []
    for path in paths:
        try:
            document = json.loads(Path(path).read_text())
        except (OSError, json.JSONDecodeError) as exc:
            print(f"skipping {path}: {exc}", file=sys.stderr)
            continue
        runs.extend(document.get("runs", []))
    return runs


def scores(runs: list[dict]) -> tuple[dict, dict, dict]:
    """Per-language and per-subject means, plus the mechanical counts."""
    by_language: dict[str, dict[str, list[int]]] = defaultdict(lambda: defaultdict(list))
    by_subject: dict[str, dict[str, list[int]]] = defaultdict(lambda: defaultdict(list))
    mechanical = defaultdict(int)
    for run in runs:
        for language in run.get("sweep", []):
            code = language.get("code")
            if code == "en":
                continue
            LANGUAGE_NAMES.setdefault(code, language.get("language", code))
            for turn in language.get("turns", []):
                mechanical["turns"] += 1
                mechanical["retries"] += turn.get("retries", 0)
                for flag in ("seed_untranslated", "outbound_untranslated", "english_zone_leak"):
                    mechanical[flag] += bool(turn.get(flag))
                for metric in ("fidelity", "fluency"):
                    score = (turn.get(metric) or {}).get("score")
                    if score is not None:
                        by_language[code][metric].append(score)
                        by_subject[run.get("subject", "?")][metric].append(score)
    return by_language, by_subject, mechanical


def mean(values: list[int]) -> float | None:
    return sum(values) / len(values) if values else None


def tier(fidelity: float | None, fluency: float | None) -> str:
    """The status rule from results-languages.md, applied identically to both systems."""
    if fidelity is None or fluency is None:
        return "-"
    if fidelity < 2.0:
        return "Blocked"
    if fidelity < 3.5 or fluency < 4.0:
        return "Review"
    return "Ready"


def cell(value: float | None) -> str:
    return f"{value:.2f}" if value is not None else "-"


def main() -> None:
    argv = sys.argv[1:]
    if "--finetuned" not in argv or "--rag" not in argv:
        raise SystemExit(__doc__)
    split = argv.index("--rag")
    finetuned_runs = load(argv[argv.index("--finetuned") + 1 : split])
    rag_runs = load(argv[split + 1 :])
    if not finetuned_runs or not rag_runs:
        raise SystemExit("need runs from both systems")

    ft_lang, ft_subject, ft_mech = scores(finetuned_runs)
    rag_lang, rag_subject, rag_mech = scores(rag_runs)

    print("# Phase 1: fine-tuned vs RAG, side by side\n")
    print("Generated by `teach2learn-portal/scripts/compare_systems.py` from both systems'")
    print("raw results files. Same lesson bank, byte-identical `translation.py`, one judge")
    print("model and one judge prompt on both sides.\n")

    print("## Mechanical checks\n")
    print("| Check | Fine-tuned | RAG |")
    print("|---|---:|---:|")
    for label, key in [
        ("Judged turns", "turns"),
        ("Untranslated participant text", "seed_untranslated"),
        ("Untranslated text shown back", "outbound_untranslated"),
        ("Native script in the English zone", "english_zone_leak"),
        ("Crossings needing a retry", "retries"),
    ]:
        print(f"| {label} | {ft_mech[key]} | {rag_mech[key]} |")

    print("\n## By language\n")
    print("Fidelity and fluency, 1-5, from the same judge under the same prompt. Delta is")
    print("RAG minus fine-tuned, so a positive fluency delta means the RAG side read better.\n")
    print("| Language | Code | FT fidelity | RAG fidelity | Δ | FT fluency | RAG fluency | Δ | FT tier | RAG tier |")
    print("|---|---|---:|---:|---:|---:|---:|---:|---|---|")
    agree = 0
    codes = sorted(set(ft_lang) | set(rag_lang), key=lambda c: -(mean(rag_lang[c]["fluency"]) or 0))
    for code in codes:
        ft_fid, ft_flu = mean(ft_lang[code]["fidelity"]), mean(ft_lang[code]["fluency"])
        rag_fid, rag_flu = mean(rag_lang[code]["fidelity"]), mean(rag_lang[code]["fluency"])
        ft_tier, rag_tier = tier(ft_fid, ft_flu), tier(rag_fid, rag_flu)
        agree += ft_tier == rag_tier
        d_fid = f"{rag_fid - ft_fid:+.2f}" if None not in (ft_fid, rag_fid) else "-"
        d_flu = f"{rag_flu - ft_flu:+.2f}" if None not in (ft_flu, rag_flu) else "-"
        print(
            f"| {LANGUAGE_NAMES.get(code, code)} | `{code}` | {cell(ft_fid)} | {cell(rag_fid)} | {d_fid} "
            f"| {cell(ft_flu)} | {cell(rag_flu)} | {d_flu} | {ft_tier} | {rag_tier} |"
        )
    print(f"\n**The two systems agree on the tier for {agree} of {len(codes)} languages.**")

    print("\n## By subject\n")
    print("| Subject | FT fidelity | RAG fidelity | FT fluency | RAG fluency |")
    print("|---|---:|---:|---:|---:|")
    for subject in sorted(set(ft_subject) | set(rag_subject)):
        print(
            f"| {SUBJECT_NAMES.get(subject, subject)} | {cell(mean(ft_subject[subject]['fidelity']))} "
            f"| {cell(mean(rag_subject[subject]['fidelity']))} | {cell(mean(ft_subject[subject]['fluency']))} "
            f"| {cell(mean(rag_subject[subject]['fluency']))} |"
        )


if __name__ == "__main__":
    main()
